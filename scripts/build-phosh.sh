#!/usr/bin/env bash
# Backport the current Phosh release against the tablet's Debian 13 libraries.
# An isolated ARM rootfs avoids replacing libraries in the production rootfs.
set -euo pipefail
cd "$(dirname "$0")/.."
project=$PWD
work=$project/.work/phosh
root=${PHOSH_BUILD_ROOT:-$work/rootfs}
artifacts=$project/.work/artifacts/current
mkdir -p "$work" "$artifacts"
if [[ ! -d $root ]]; then
    [[ -r .work/rootfs/etc/debian_version ]] || { echo 'Prepare the Debian rootfs first'; exit 1; }
    sudo cp -a --reflink=auto .work/rootfs "$root"
fi
[[ $(sudo chroot "$root" dpkg --print-architecture) == armhf ]]
[[ $(sudo chroot "$root" /bin/sh -c '. /etc/os-release; echo "$VERSION_CODENAME"') == trixie ]]
fetch() {
    [[ -f $work/$2 ]] || curl -fL --retry 3 "$1" -o "$work/$2"
}
fetch https://sources.phosh.mobi/releases/phosh/phosh-0.58.0.tar.xz phosh-0.58.0.tar.xz
fetch https://deb.debian.org/debian/pool/main/p/phosh/phosh_0.58.0-1.debian.tar.xz phosh_0.58.0-1.debian.tar.xz
(cd "$work"; sha256sum -c <<'SUMS'
b936af34ebed15b29d4f941c48aa328a47da9c2e51cbf6ef89040a90f522ed73  phosh-0.58.0.tar.xz
dc9b725c576ab5462c01119453372bac7b8c15bf5b93f8a8b148d8c69ab29fe7  phosh_0.58.0-1.debian.tar.xz
SUMS
)
sudo chroot "$root" /bin/sh -c 'printf "#!/bin/sh\nexit 101\n" >/usr/sbin/policy-rc.d; chmod 755 /usr/sbin/policy-rc.d'
sudo chroot "$root" env DEBIAN_FRONTEND=noninteractive apt-get -y --no-install-recommends install \
    build-essential debhelper dh-sequence-gir gobject-introspection valac \
    meson ninja-build pkgconf gettext universal-ctags desktop-file-utils \
    libappstream-dev libecal2.0-dev evolution-data-server-dev libfribidi-dev \
    libgcr-3-dev libglib2.0-dev libgirepository1.0-dev libgnome-bluetooth-3.0-dev \
    libgmobile-dev libgnome-desktop-3-dev gsettings-desktop-schemas-dev \
    gnome-settings-daemon-common \
    libgtk-3-dev libgudev-1.0-dev libfeedback-dev libhandy-1-dev libnm-dev \
    libpolkit-agent-1-dev libsoup-3.0-dev libsystemd-dev libmm-glib-dev \
    libsecret-1-dev libupower-glib-dev libwayland-dev wayland-protocols \
    libpulse-dev libcallaudio-dev libpam0g-dev libqrcodegen-dev libjson-glib-dev \
    libadwaita-1-dev libevince-dev
source=$root/build-phosh
if [[ ! -f $source/meson.build ]]; then
    sudo tar -xf "$work/phosh-0.58.0.tar.xz" -C "$root"
    sudo mv "$root/phosh-0.58.0" "$source"
    sudo tar -xf "$work/phosh_0.58.0-1.debian.tar.xz" -C "$source"
fi
for patch in "$project"/patches/phosh/*.patch; do
    name=$(basename "$patch")
    sudo install -m644 "$patch" "$source/debian/patches/$name"
    if ! sudo grep -qxF "$name" "$source/debian/patches/series"; then
        printf '%s\n' "$name" | sudo tee -a "$source/debian/patches/series" >/dev/null
    fi
done
sudo python3 - "$source/debian/changelog" <<'PY'
from pathlib import Path
import sys
p = Path(sys.argv[1])
text = p.read_text()
if not text.startswith('phosh (0.58.0-1~t5313)'):
    p.write_text('''phosh (0.58.0-1~t5313) trixie; urgency=medium

  * Rebuild Debian's current release against Debian 13 for SM-T531.
  * Keep legacy brightness shortcuts when the GNOME 49 schema is absent.
  * Require an available ambient light sensor for automatic brightness.

 -- T531 Project <noreply@localhost>  Sat, 17 Oct 2026 02:35:00 +0000

''' + text)
PY
# Debian sid renamed two development packages; the installed trixie headers
# provide the same pkg-config APIs. Runtime dependencies are generated by dpkg.
sudo sed -i -e 's/libevince-gtk3-dev/libevince-dev/' \
    -e 's/libhandy-dev/libhandy-1-dev/' "$source/debian/control"
if [[ ${PHOSH_INCREMENTAL:-0} == 1 ]]; then
    sudo chroot "$root" /bin/sh -c \
        'cd /build-phosh; dpkg-source --before-build .; ninja -C obj-arm-linux-gnueabihf -j8'
    build_flags=(-nc)
else
    build_flags=()
fi
sudo chroot "$root" env DEB_BUILD_PROFILES=nodoc \
    DEB_BUILD_OPTIONS="nocheck parallel=${JOBS:-8}" \
    /bin/sh -c 'cd /build-phosh; exec dpkg-buildpackage -b -uc -us -d "$@"' sh "${build_flags[@]}"
# -d only skips sid's renamed build-dependency metadata above; compiler/linker
# checks remain enabled. GUI-dependent upstream tests are not hardware evidence.
sudo cp "$root"/*_0.58.0-1~t5313_*.deb "$artifacts/"
sudo chroot "$root" dpkg-query -W >"$work/build-packages.txt"
(cd "$artifacts"; sha256sum *_0.58.0-1~t5313_*.deb >phosh-packages.sha256)
echo "Phosh 0.58.0 Debian 13 packages: $artifacts"
