#!/usr/bin/env bash
# Run on the tablet with the rebuilt Phosh packages; no package removals allowed.
set -euo pipefail
[[ $EUID == 0 ]]
tr '\0' '\n' </proc/device-tree/compatible | grep -qx samsung,matisse3g
project=$(realpath "$(dirname "$0")/..")
release=$(realpath "${1:?Usage: install-phosh.sh PHOSH_RELEASE_DIRECTORY}")
runtime=/var/cache/t531/phosh-runtime
backup=/var/lib/t531/phosh-install-before-$(date -u +%Y%m%dT%H%M%SZ)
exec 9>/run/lock/t531-graphics-profile.lock
flock -n 9 || { echo 'A graphics recording is active'; exit 1; }
mkdir -m700 "$backup"
dpkg-query -W -f='${binary:Package} ${Version} ${db:Status-Status}\n' >"$backup/packages.txt"
cp -a /etc/sddm.conf.d /etc/systemd/system/sddm.service.d "$backup/"
python3 "$project/tools/fetch-phosh-runtime.py" "$runtime"
packages=()
for spec in phosh:armhf phosh-common:all libphosh-0.45-0:armhf phosh-plugins:armhf; do
    package=${spec%:*}; architecture=${spec#*:}
    file=$release/${package}_0.58.0-1~t5313_${architecture}.deb
    [[ $(dpkg-deb -f "$file" Package) == "$package" ]]
    [[ $(dpkg-deb -f "$file" Version) == 0.58.0-1~t5313 ]]
    [[ $(dpkg-deb -f "$file" Architecture) == "$architecture" ]]
    packages+=("$file")
done
# The full host-built manifest is generated by build-phosh.sh.
[[ -r $release/phosh-packages.sha256 ]]
(cd "$release"; sha256sum --check --ignore-missing phosh-packages.sha256)
mapfile -t runtime_files < <(python3 - "$project/config/phosh-runtime.lock.json" "$runtime" <<'PY'
import json, pathlib, sys
for entry in json.load(open(sys.argv[1]))['packages']:
    print(pathlib.Path(sys.argv[2]) / entry['filename'])
PY
)
apt-get -s --no-install-recommends --no-remove install "${packages[@]}" \
    "${runtime_files[@]}" phosh-mobile-settings squeekboard gnome-keyring \
    feedbackd wlr-randr librsvg2-common gnome-backgrounds
systemctl stop sddm
DEBIAN_FRONTEND=noninteractive apt-get -y --no-install-recommends --no-remove install \
    "${packages[@]}" "${runtime_files[@]}" phosh-mobile-settings squeekboard \
    gnome-keyring feedbackd wlr-randr librsvg2-common gnome-backgrounds
dpkg --audit
apt-get check
bash "$project/scripts/select-mobile-shell.sh" phosh
